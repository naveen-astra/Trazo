#!/usr/bin/env python3
"""Generate deploy/.env.production with fresh random secrets.

    python scripts/prod/init_env.py --domain trazo.example.com --email ops@example.com

Every secret is drawn from the OS CSPRNG (``secrets``) and is URL-safe, so
it can be embedded in the database and Redis connection URLs without
escaping. The file is written owner-read-only where the platform supports
it. The dashboard password and API key are printed once so they can be
stored in a password manager; they are not recoverable from anywhere else
except the file itself.

Stdlib only. Refuses to overwrite an existing file without ``--force``,
because regenerating the database password against an already-initialized
database volume locks the control plane out of its own data.
"""

from __future__ import annotations

import argparse
import contextlib
import os
import re
import secrets
import stat
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
ENV_FILE = REPO_ROOT / "deploy" / ".env.production"

# A bare hostname: no scheme, port, or path.
_DOMAIN_RE = re.compile(
    r"^(?=.{1,253}$)(?!-)[a-z0-9-]{1,63}(?<!-)(\.(?!-)[a-z0-9-]{1,63}(?<!-))*$"
)
_EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--domain",
        required=True,
        help="public hostname the dashboard is served on, e.g. trazo.example.com",
    )
    parser.add_argument(
        "--email",
        required=True,
        help="contact address for TLS certificate expiry notices",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="overwrite an existing deploy/.env.production (see the module docstring)",
    )
    return parser.parse_args()


def main() -> int:
    args = _parse_args()
    domain = args.domain.strip().lower()
    email = args.email.strip()

    if not _DOMAIN_RE.match(domain) or "." not in domain:
        print(
            "error: --domain must be a bare hostname like trazo.example.com, "
            f"got {args.domain!r}",
            file=sys.stderr,
        )
        return 2
    if not _EMAIL_RE.match(email):
        print(
            f"error: --email does not look like an address: {email!r}", file=sys.stderr
        )
        return 2
    if ENV_FILE.exists() and not args.force:
        print(
            f"error: {ENV_FILE.relative_to(REPO_ROOT)} already exists. "
            "Re-running this would\n"
            "replace the database password, which an initialized database volume will\n"
            "then reject. Edit the file directly, or pass --force on a fresh install.",
            file=sys.stderr,
        )
        return 1

    api_key = secrets.token_urlsafe(36)
    dashboard_password = secrets.token_urlsafe(18)

    contents = f"""\
# Trazo production configuration. Generated by scripts/prod/init_env.py.
# Contains live credentials: never commit it (it is gitignored), and keep
# its permissions owner-only.

# --- public endpoint ---
TRAZO_DOMAIN={domain}
ACME_EMAIL={email}

# --- dashboard sign-in ---
TRAZO_DASHBOARD_PASSWORD={dashboard_password}
TRAZO_SESSION_SECRET={secrets.token_urlsafe(48)}
TRAZO_SESSION_TTL_HOURS=12

# --- SDK, CLI and ingest (send as "Authorization: Bearer <key>") ---
TRAZO_API_KEY={api_key}

# --- datastores (internal network only; never published) ---
POSTGRES_USER=trazo
POSTGRES_DB=trazo
POSTGRES_PASSWORD={secrets.token_urlsafe(32)}
REDIS_PASSWORD={secrets.token_urlsafe(32)}

# --- host ports (change only if 80/443 are taken by another service) ---
HTTP_PORT=80
HTTPS_PORT=443
"""

    ENV_FILE.write_text(contents, encoding="utf-8", newline="\n")
    with contextlib.suppress(OSError):  # Windows ACLs: chmod is advisory there.
        os.chmod(ENV_FILE, stat.S_IRUSR | stat.S_IWUSR)

    print(f"Wrote {ENV_FILE.relative_to(REPO_ROOT)} (owner read/write only).")
    print()
    print("Store these in a password manager now. They are shown only once:")
    print()
    print(f"  Dashboard URL       https://{domain}")
    print(f"  Dashboard password  {dashboard_password}")
    print(f"  API key (SDK/CLI)   {api_key}")
    print()
    print("Next:")
    print(f"  1. Point the DNS A record for {domain} at this server's public IP.")
    print("  2. Open ports 80 and 443 in the server firewall.")
    print("  3. make prod-up")
    return 0


if __name__ == "__main__":
    sys.exit(main())
